def _render_project_selector(
    projects: list[Project],
) -> Project | None:
    """
    Render project selection.
    """

    if not projects:
        st.warning(
            "No projects are available. "
            "Create a project before running Generative Design."
        )

        return None

    project_options = {
        str(project.id): project
        for project in projects
    }

    current_project_id = (
        st.session_state.gd_project_id
    )

    option_ids = list(
        project_options.keys()
    )

    default_index = 0

    if current_project_id is not None:

        current_key = str(
            current_project_id
        )

        if current_key in option_ids:
            default_index = option_ids.index(
                current_key
            )

    selected_key = st.selectbox(
        "Project",
        options=option_ids,
        index=default_index,
        format_func=lambda value: (
            project_options[value].name
        ),
        key="gd_project_selector",
    )

    selected_project = project_options[
        selected_key
    ]

    selected_id = _object_id(
        selected_project
    )

    if selected_id is not None:

        if (
            st.session_state.gd_project_id
            != selected_id
        ):
            st.session_state.gd_project_id = (
                selected_id
            )

            st.session_state.gd_project_name = (
                selected_project.name
            )

            st.session_state.gd_selected_run_id = None
            st.session_state.gd_selected_candidate_id = None
            st.session_state.gd_best_candidate_id = None

    return selected_project


