def _run_async(
    coroutine_factory: Any,
) -> Any:
    """
    Execute an async operation safely from Streamlit.

    Streamlit normally executes synchronously, but an existing
    event loop may exist in some environments.

    Instead of calling asyncio.run() directly on the Streamlit
    execution thread, this function executes the coroutine inside
    a dedicated worker thread with its own event loop.

    Parameters
    ----------
    coroutine_factory:
        Callable returning an awaitable.

    Returns
    -------
    Any
        Result returned by the coroutine.

    Raises
    ------
    BaseException
        Re-raises the exception generated by the worker coroutine.
    """

    result: dict[str, Any] = {}
    error: dict[str, BaseException] = {}

    def runner() -> None:
        try:
            result["value"] = asyncio.run(
                coroutine_factory()
            )
        except BaseException as exc:
            error["exception"] = exc

    thread = threading.Thread(
        target=runner,
        daemon=True,
    )

    thread.start()
    thread.join()

    if "exception" in error:
        raise error["exception"]

    return result.get("value")


