def _initialize_state() -> None:
    """
    Initialize Generative Design UI state.
    """

    defaults: dict[str, Any] = {
        "gd_project_id": None,
        "gd_project_name": None,
        "gd_selected_run_id": None,
        "gd_selected_candidate_id": None,
        "gd_best_candidate_id": None,
        "gd_last_generation": None,
        "gd_generation_error": None,
        "gd_show_run_history": False,
        "gd_generation_requested": False,
    }

    for key, value in defaults.items():
        if key not in st.session_state:
            st.session_state[key] = value


