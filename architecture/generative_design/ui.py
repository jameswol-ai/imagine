# ============================================================================
# REGENERATION
# ============================================================================

def _render_regeneration(
    project: Project,
) -> None:
    """
    Render regeneration controls.

    Regeneration delegates completely to the existing service layer.
    """

    st.divider()

    st.subheader(
        "Regenerate"
    )

    st.caption(
        "Generate a new candidate population using the project's "
        "current constraints."
    )

    project_id = _object_id(
        project
    )

    if project_id is None:
        return

    col1, col2 = st.columns(
        2
    )

    with col1:

        regenerate_count = st.number_input(
            "New candidate count",
            min_value=1,
            max_value=500,
            value=20,
            step=1,
            key="gd_regenerate_count",
        )

    with col2:

        regenerate_diversity = st.slider(
            "New diversity",
            min_value=0.0,
            max_value=1.0,
            value=0.80,
            step=0.05,
            key="gd_regenerate_diversity",
        )

    if st.button(
        "🔄 Regenerate Designs",
        use_container_width=True,
        key="gd_regenerate_button",
    ):

        parameters = {
            "candidate_count": int(
                regenerate_count
            ),
            "diversity": float(
                regenerate_diversity
            ),
            "ranking_strategy": "balanced",
            "regeneration": True,
        }

        st.session_state.gd_generation_error = None

        progress = st.progress(
            0,
            text="Preparing regeneration...",
        )

        status = st.empty()

        try:

            progress.progress(
                20,
                text="Loading current constraints...",
            )

            status.info(
                "Regenerating from the current project constraints."
            )

            progress.progress(
                50,
                text="Generating new design population...",
            )

            result = _run_async(
                lambda: _generate_designs(
                    project_id,
                    parameters,
                )
            )

            progress.progress(
                85,
                text="Persisting and ranking regenerated candidates...",
            )

            run_id = _extract_run_id(
                result
            )

            if run_id is not None:

                st.session_state.gd_selected_run_id = (
                    run_id
                )

            progress.progress(
                100,
                text="Regeneration completed.",
            )

            status.success(
                "New design candidates generated successfully."
            )

            st.rerun()

        except Exception as exc:

            progress.progress(
                100,
                text="Regeneration failed.",
            )

            st.session_state.gd_generation_error = (
                str(exc)
            )

            status.error(
                "Regeneration failed."
            )

            st.exception(exc)


# ============================================================================
# ERROR STATE
# ============================================================================

def _render_error_state() -> None:
    """
    Display the most recent generation error.
    """

    error = (
        st.session_state.gd_generation_error
    )

    if not error:
        return

    st.error(
        "Generative Design Error"
    )

    st.code(
        str(error)
    )

    if st.button(
        "Clear Error",
        key="gd_clear_error",
    ):

        st.session_state.gd_generation_error = None

        st.rerun()


# ============================================================================
# MAIN UI
# ============================================================================

def render_generative_design() -> None:
    """
    Render the complete Generative Design interface.

    This is the function imported by streamlit_app.py:

        from architecture.generative_design.ui import (
            render_generative_design,
        )

    and called with:

        render_generative_design()
    """

    _initialize_state()

    # ------------------------------------------------------------------
    # Header
    # ------------------------------------------------------------------

    st.title(
        "✨ Generative Design"
    )

    st.caption(
        "Constraint-driven architectural design generation, "
        "evaluation and ranking."
    )

    # ------------------------------------------------------------------
    # Project loading
    # ------------------------------------------------------------------

    try:

        projects = _run_async(
            _load_projects
        )

    except Exception as exc:

        st.error(
            "Unable to load projects."
        )

        st.exception(exc)

        return

    # ------------------------------------------------------------------
    # Project selection
    # ------------------------------------------------------------------

    project = _render_project_selector(
        projects
    )

    if project is None:
        return

    # ------------------------------------------------------------------
    # Project summary
    # ------------------------------------------------------------------

    st.markdown(
        f"## 📁 {project.name}"
    )

    if project.description:

        st.caption(
            project.description
        )

    # ------------------------------------------------------------------
    # Constraint summary
    # ------------------------------------------------------------------

    _render_constraint_summary(
        project
    )

    st.divider()

    # ------------------------------------------------------------------
    # Generation parameters
    # ------------------------------------------------------------------

    parameters = _render_generation_parameters()

    st.divider()

    # ------------------------------------------------------------------
    # Generation controls
    # ------------------------------------------------------------------

    _render_generation_controls(
        project,
        parameters,
    )

    # ------------------------------------------------------------------
    # Error state
    # ------------------------------------------------------------------

    _render_error_state()

    # ------------------------------------------------------------------
    # Last/current run
    # ------------------------------------------------------------------

    selected_run_id = (
        st.session_state.gd_selected_run_id
    )

    if selected_run_id is not None:

        try:

            current_run = _run_async(
                lambda: _load_run(
                    selected_run_id
                )
            )

        except Exception as exc:

            st.error(
                "Unable to load the generation run."
            )

            st.exception(exc)

            current_run = None

        if current_run is not None:

            _render_run_summary(
                current_run
            )

            _render_candidates(
                current_run
            )

    # ------------------------------------------------------------------
    # Candidate inspection
    # ------------------------------------------------------------------

    _render_candidate_inspection()

    # ------------------------------------------------------------------
    # Regeneration
    # ------------------------------------------------------------------

    _render_regeneration(
        project
    )

    # ------------------------------------------------------------------
    # Run history
    # ------------------------------------------------------------------

    _render_run_history(
        project
        )
