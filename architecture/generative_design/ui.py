def _build_service(
    session: Any,
) -> GenerativeDesignService:
    """
    Construct the GenerativeDesignService.

    The current architecture uses AsyncSession as the service
    dependency.

    If the service exposes a different constructor signature,
    this helper keeps construction isolated to one location.
    """

    try:
        return GenerativeDesignService(
            session
        )
    except TypeError:

        repository = GenerativeDesignRepository(
            session
        )

        return GenerativeDesignService(
            session=session,
            repository=repository,
        )


async def _generate_designs(
    project_id: UUID,
    parameters: dict[str, Any],
) -> Any:
    """
    Execute GenerativeDesignService.generate().

    The service owns:
        - constraint loading
        - validation
        - generation
        - scoring
        - candidate persistence
        - candidate_count update
        - completion/failure state
        - transaction commit/rollback
    """

    async with AsyncSessionLocal() as session:

        service = _build_service(
            session
        )

        generate_method = getattr(
            service,
            "generate",
            None,
        )

        if generate_method is None:
            raise AttributeError(
                "GenerativeDesignService.generate() "
                "does not exist."
            )

        signature = inspect.signature(
            generate_method
        )

        kwargs: dict[str, Any] = {}

        parameters_available = signature.parameters

        if "project_id" in parameters_available:
            kwargs["project_id"] = project_id

        if "parameters" in parameters_available:
            kwargs["parameters"] = parameters

        elif "options" in parameters_available:
            kwargs["options"] = parameters

        elif "generation_parameters" in parameters_available:
            kwargs[
                "generation_parameters"
            ] = parameters

        elif "settings" in parameters_available:
            kwargs["settings"] = parameters

        # If generate() expects only positional arguments,
        # support the common project_id / parameters contract.
        if kwargs:
            return await generate_method(
                **kwargs
            )

        return await generate_method(
            project_id,
            parameters,
        )


# ============================================================================
# NORMALIZATION HELPERS
# ============================================================================

def _object_id(
    value: Any,
) -> UUID | None:
    """
    Extract a UUID from an ORM object or UUID value.
    """

    if value is None:
        return None

    if isinstance(value, UUID):
        return value

    object_id = getattr(
        value,
        "id",
        None,
    )

    if object_id is None:
        return None

    if isinstance(object_id, UUID):
        return object_id

    try:
        return UUID(
            str(object_id)
        )
    except (TypeError, ValueError):
        return None


def _as_dict(
    value: Any,
) -> dict[str, Any]:
    """
    Safely normalize JSON-like values for UI display.
    """

    if value is None:
        return {}

    if isinstance(value, dict):
        return value

    try:
        return dict(value)
    except (TypeError, ValueError):
        return {
            "value": value
        }


def _format_datetime(
    value: Any,
) -> str:
    """
    Format datetime values for the UI.
    """

    if value is None:
        return "—"

    if isinstance(
        value,
        datetime,
    ):
        return value.strftime(
            "%Y-%m-%d %H:%M"
        )

    return str(value)


def _run_status_icon(
    status: str | None,
) -> str:
    """
    Return a visual status icon.
    """

    icons = {
        RUN_STATUS_PENDING: "⏳",
        RUN_STATUS_RUNNING: "⚙️",
        RUN_STATUS_COMPLETED: "✅",
        RUN_STATUS_FAILED: "❌",
    }

    return icons.get(
        status or "",
        "•",
    )


