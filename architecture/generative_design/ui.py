async def _load_projects() -> list[Project]:
    """
    Load available projects asynchronously.
    """

    async with AsyncSessionLocal() as session:

        statement = (
            select(Project)
            .order_by(
                Project.name.asc()
            )
        )

        result = await session.execute(
            statement
        )

        return list(
            result.scalars().all()
        )


async def _load_run(
    run_id: UUID,
) -> GenerativeDesignRun | None:
    """
    Load one generation run with candidates.
    """

    async with AsyncSessionLocal() as session:

        repository = GenerativeDesignRepository(
            session
        )

        return await repository.get_run_with_candidates(
            run_id
        )


async def _load_runs(
    project_id: UUID,
) -> list[GenerativeDesignRun]:
    """
    Load generation history for a project.
    """

    async with AsyncSessionLocal() as session:

        repository = GenerativeDesignRepository(
            session
        )

        runs = await repository.list_runs(
            project_id=project_id,
            limit=100,
        )

        return list(runs)


async def _load_candidate(
    candidate_id: UUID,
) -> DesignCandidateRecord | None:
    """
    Load one candidate.
    """

    async with AsyncSessionLocal() as session:

        repository = GenerativeDesignRepository(
            session
        )

        return await repository.get_candidate(
            candidate_id
        )


