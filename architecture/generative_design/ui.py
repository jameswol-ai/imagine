# ============================================================================
# GENERATION
# ============================================================================

def _render_generation_controls(
    project: Project,
    parameters: dict[str, Any],
) -> None:
    """
    Render generation and regeneration actions.
    """

    st.subheader(
        "Generate Design Options"
    )

    generate_col, history_col = st.columns(
        [2, 1]
    )

    with generate_col:

        generate = st.button(
            "✨ Generate Design Options",
            type="primary",
            use_container_width=True,
            key="gd_generate_button",
        )

    with history_col:

        history = st.button(
            "📜 Run History",
            use_container_width=True,
            key="gd_history_button",
        )

    if history:
        st.session_state.gd_show_run_history = (
            not st.session_state.gd_show_run_history
        )

    if not generate:
        return

    project_id = _object_id(
        project
    )

    if project_id is None:
        st.error(
            "The selected project does not have a valid UUID."
        )
        return

    st.session_state.gd_generation_error = None
    st.session_state.gd_last_generation = None
    st.session_state.gd_generation_requested = True

    progress = st.progress(
        0,
        text="Preparing generative design run...",
    )

    status_box = st.empty()

    try:

        progress.progress(
            10,
            text="Loading project constraints...",
        )

        status_box.info(
            "Collecting Zoning, Site Planning, Floor Planning, "
            "Room Programming and Compliance constraints."
        )

        progress.progress(
            30,
            text="Generating candidate designs...",
        )

        result = _run_async(
            lambda: _generate_designs(
                project_id,
                parameters,
            )
        )

        progress.progress(
            80,
            text="Persisting and ranking candidates...",
        )

        st.session_state.gd_last_generation = (
            result
        )

        progress.progress(
            100,
            text="Generation completed.",
        )

        status_box.success(
            "Generative design run completed successfully."
        )

        run_id = _extract_run_id(
            result
        )

        if run_id is not None:
            st.session_state.gd_selected_run_id = (
                run_id
            )

        st.rerun()

    except Exception as exc:

        progress.progress(
            100,
            text="Generation failed.",
        )

        st.session_state.gd_generation_error = (
            str(exc)
        )

        status_box.error(
            "Generative design generation failed."
        )

        st.exception(exc)


# ============================================================================
# RESULT EXTRACTION
# ============================================================================

def _extract_run_id(
    result: Any,
) -> UUID | None:
    """
    Extract the generated run UUID from common service return forms.
    """

    if result is None:
        return None

    if isinstance(
        result,
        UUID,
    ):
        return result

    if isinstance(
        result,
        dict,
    ):

        for key in (
            "run_id",
            "id",
        ):

            if key in result:
                return _object_id(
                    result[key]
                )

    return _object_id(
        result
    )


# ============================================================================
# RUN HISTORY
# ============================================================================

def _render_run_history(
    project: Project,
) -> None:
    """
    Render generation run history.
    """

    if not st.session_state.gd_show_run_history:
        return

    project_id = _object_id(
        project
    )

    if project_id is None:
        return

    st.divider()

    st.subheader(
        "Generation Run History"
    )

    try:

        runs = _run_async(
            lambda: _load_runs(
                project_id
            )
        )

    except Exception as exc:

        st.error(
            "Unable to load generation history."
        )

        st.exception(exc)

        return

    if not runs:

        st.info(
            "No generative design runs exist for this project yet."
        )

        return

    rows = []

    for run in runs:

        rows.append(
            {
                "Run": str(run.id),
                "Status": (
                    f"{_run_status_icon(run.status)} "
                    f"{run.status}"
                ),
                "Candidates": run.candidate_count,
                "Created": _format_datetime(
                    run.created_at
                ),
                "Completed": _format_datetime(
                    run.completed_at
                ),
            }
        )

    history_df = pd.DataFrame(
        rows
    )

    st.dataframe(
        history_df,
        use_container_width=True,
        hide_index=True,
    )

    run_ids = [
        str(run.id)
        for run in runs
    ]

    selected_history_run = st.selectbox(
        "Inspect run",
        options=run_ids,
        format_func=lambda value: (
            next(
                (
                    f"{value} · "
                    f"{next_run.status} · "
                    f"{next_run.candidate_count} candidates"
                    for next_run in runs
                    if str(next_run.id) == value
                ),
                value,
            )
        ),
        key="gd_history_run_selector",
    )

    if selected_history_run:

        try:

            selected_run = _run_async(
                lambda: _load_run(
                    UUID(
                        selected_history_run
                    )
                )
            )

            if selected_run is not None:

                st.session_state.gd_selected_run_id = (
                    selected_run.id
                )

                _render_run_summary(
                    selected_run
                )

                _render_candidates(
                    selected_run
                )

        except Exception as exc:

            st.error(
                "Unable to load the selected run."
            )

            st.exception(exc)


